use std::cell::RefCell;
use std::collections::{HashMap, HashSet};
use std::path::PathBuf;
use std::rc::Rc;

use crate::engine::{self, Doc, Project};
use crate::loader::{Kind, Node};

use super::page::{TreeNode, reserved};
use super::text::is_empty;

pub const HEADER: &str = "<!-- GENERATED by docc, DO NOT EDIT -->";

/// Backrefs maps a document id to the documents that point at it.
pub(super) type Backrefs<'a> = Rc<HashMap<String, Vec<&'a Doc>>>;

/// Renderer builds the files of one build.
pub struct Renderer<'a> {
    pub p: &'a Project,
    pub full: bool,

    pub(super) back: RefCell<Option<Backrefs<'a>>>,
    pub(super) slugs: RefCell<HashMap<*const Doc, Rc<HashMap<*const Node, AnchorInfo>>>>,
    /// page numbers by document id; None until number_of runs
    pub(super) nums: RefCell<Option<Rc<HashMap<String, String>>>>,
    /// single-file build: links are in-file anchors, no Header per page
    pub(super) single: bool,
    /// single Markdown file: emit <a id> before pages and field headings
    pub(super) anchors: bool,
    /// single HTML file: pages carry only body and fields
    pub(super) html: bool,
    /// images the pages show, paths relative to src; collected by Files
    pub(super) imgs: RefCell<Option<HashSet<String>>>,
    /// the readers' comments are shown ("$comments"); false: build --no-comments
    pub comments: bool,
    /// the Git revision the HTML file counts the edits from (build --since); "" for none
    pub since: String,
    /// the id of the one page the build writes (build --page); "" for every page
    pub only: String,
}

impl<'a> Renderer<'a> {
    /// new is &render.Renderer{P: p, Full: full}.
    pub fn new(p: &'a Project, full: bool) -> Renderer<'a> {
        Renderer {
            p,
            full,
            back: RefCell::new(None),
            slugs: RefCell::new(HashMap::new()),
            nums: RefCell::new(None),
            single: false,
            anchors: false,
            html: false,
            imgs: RefCell::new(None),
            comments: true,
            since: String::new(),
            only: String::new(),
        }
    }

    /// variant is a copy of r with other build flags (Go: s := *r). The caches
    /// do not depend on the flags, so they start empty.
    pub(super) fn variant(&self, single: bool, anchors: bool, html: bool) -> Renderer<'a> {
        Renderer {
            single,
            anchors,
            html,
            comments: self.comments,
            since: self.since.clone(),
            only: self.only.clone(),
            ..Renderer::new(self.p, self.full)
        }
    }

    /// Files returns every generated file: path relative to the output directory
    /// ('/' separators) to content. The images the pages show are copied from src
    /// at the same path; their content is the bytes of the file. Call it only when
    /// validation found no errors of groups 1xx and 2xx.
    pub fn files(&self) -> HashMap<String, Vec<u8>> {
        let mut out = HashMap::new();
        *self.imgs.borrow_mut() = Some(HashSet::new());
        for d in self.docs().into_iter().filter(|d| self.writes(d)) {
            out.insert(page_path(d), lf(&self.page(d)).into_bytes());
        }
        if self.only.is_empty() {
            out.insert("_tree.md".to_string(), lf(&self.tree()).into_bytes());
        }
        let imgs = self.imgs.borrow_mut().take().unwrap_or_default();
        for rel in imgs {
            if let Ok(b) = self.p.cfg.source.read(&self.src_file(&rel)) {
                // DOC213 reports a missing file
                out.insert(rel, b);
            }
        }
        out
    }

    /// srcFile is the OS path of a file given relative to src.
    pub(super) fn src_file(&self, rel: &str) -> PathBuf {
        self.p.cfg.abs(&format!("{}/{}", self.p.cfg.src, rel))
    }

    /// Single returns every page in one Markdown file: the document tree first,
    /// then the pages in tree order. Links become in-file anchors. Same call
    /// contract as Files.
    pub fn single(&self) -> String {
        let s = self.variant(true, true, false);
        let mut blocks = vec![HEADER.to_string()];
        if s.only.is_empty() {
            blocks.extend(s.tree_blocks());
        }
        for d in s.pages() {
            blocks.push("---".into());
            blocks.push(s.page(d));
        }
        lf(&blocks.join("\n\n")) + "\n"
    }

    /// ordered returns the pages in tree order; documents the tree walk cannot reach
    /// (a parent cycle) follow, so that nothing is lost.
    pub(super) fn ordered(&self) -> Vec<&'a Doc> {
        let mut seen = HashSet::new();
        let mut out = Vec::new();
        if self.p.cfg.folders {
            fn walk<'a>(ns: &[TreeNode<'a>], out: &mut Vec<&'a Doc>) {
                for n in ns {
                    out.extend(n.page());
                    walk(n.kids(), out);
                }
            }
            walk(&self.tree_nodes(), &mut out);
            seen.extend(out.iter().map(|d| d.id.as_str()));
        } else {
            let (tree, orphans) = self.layout();
            for e in tree.iter().chain(&orphans) {
                seen.insert(e.d.id.as_str());
                out.push(e.d);
            }
        }
        for d in self.docs() {
            if !seen.contains(d.id.as_str()) {
                out.push(d);
            }
        }
        out
    }

    /// page_id is the id of the page build --page names: its path relative to
    /// src as docc compile gives it, with or without ".json", or its id; None
    /// when no page of this build has that name.
    pub fn page_id(&self, name: &str) -> Option<String> {
        let name = name.replace('\\', "/");
        let docs = self.docs();
        docs.iter()
            .find(|d| d.rel == name || d.rel.strip_suffix(".json") == Some(name.as_str()))
            .or_else(|| docs.iter().find(|d| d.id == name))
            .map(|d| d.id.clone())
    }

    /// pages are the pages the build writes, in tree order: every page, or
    /// the one of build --page.
    pub(super) fn pages(&self) -> Vec<&'a Doc> {
        self.ordered().into_iter().filter(|d| self.writes(d)).collect()
    }

    fn writes(&self, d: &Doc) -> bool {
        self.only.is_empty() || d.id == self.only
    }

    /// docs returns the documents that get a page, ordered by path.
    pub(super) fn docs(&self) -> Vec<&'a Doc> {
        let p: &'a Project = self.p;
        let mut out: Vec<&'a Doc> = p
            .docs
            .iter()
            .filter(|d| self.in_graph(d) && d.parsed() && (self.full || !d.hidden))
            .collect();
        out.sort_by(|a, b| a.rel.cmp(&b.rel));
        out
    }

    /// in_graph reports whether d is the graph node of its id (Go: P.Graph[d.ID] == d).
    fn in_graph(&self, d: &Doc) -> bool {
        self.p.doc(&d.id).is_some_and(|g| std::ptr::eq(g, d))
    }

    /// hasPage reports whether links may point at the document.
    pub(super) fn has_page(&self, d: Option<&Doc>) -> bool {
        d.is_some_and(|d| self.in_graph(d) && d.parsed() && (self.full || !d.hidden))
    }

    /// numberOf returns the number of a page ("2.1"), or "" when numbering is off
    /// or the page has none: roots, pages without a visible parent chain, hidden
    /// pages. Numbers come from the tree without hidden documents, so the full
    /// build shows the same numbers.
    pub(super) fn number_of(&self, d: &Doc) -> String {
        if !self.p.cfg.numbering {
            return String::new();
        }
        let nums = self.nums.borrow().clone();
        let nums = match nums {
            Some(n) => n,
            None => {
                let mut nums = HashMap::new();
                let v = Renderer::new(self.p, false);
                if self.p.cfg.folders {
                    // every entry of the folder tree is numbered among its siblings: 1, 1.2
                    fn walk(ns: &[TreeNode<'_>], prefix: &str, nums: &mut HashMap<String, String>) {
                        for (i, n) in ns.iter().enumerate() {
                            let num = if prefix.is_empty() { (i + 1).to_string() } else { format!("{prefix}.{}", i + 1) };
                            if let TreeNode::Folder { path, .. } = n {
                                nums.insert(format!("/{path}"), num.clone());
                            }
                            if let Some(d) = n.page() {
                                nums.insert(d.id.clone(), num.clone());
                            }
                            walk(n.kids(), &num, nums);
                        }
                    }
                    walk(&v.tree_nodes(), "", &mut nums);
                }
                let (tree, _) = if self.p.cfg.folders { (Vec::new(), Vec::new()) } else { v.layout() };
                let mut stack: Vec<String> = Vec::new(); // number of the current entry at each depth
                let mut count: HashMap<String, usize> = HashMap::new();
                for e in tree {
                    stack.truncate(e.depth);
                    let mut num = String::new();
                    if e.depth > 0 {
                        let parent = stack[e.depth - 1].clone(); // "" for a root: its children count across all roots
                        let c = count.entry(parent.clone()).or_default();
                        *c += 1;
                        num = c.to_string();
                        if !parent.is_empty() {
                            num = format!("{parent}.{num}");
                        }
                        nums.insert(e.d.id.clone(), num.clone());
                    }
                    stack.push(num);
                }
                let nums = Rc::new(nums);
                *self.nums.borrow_mut() = Some(nums.clone());
                nums
            }
        };
        nums.get(&d.id).cloned().unwrap_or_default()
    }

    /// folder_number is the number of a folder (path relative to src) in
    /// folder mode, "" when numbering is off.
    pub(super) fn folder_number(&self, path: &str) -> String {
        if !self.p.cfg.numbering {
            return String::new();
        }
        let Some(any) = self.p.docs.first() else {
            return String::new();
        };
        self.number_of(any); // fills the cache
        self.nums.borrow().as_ref().and_then(|n| n.get(&format!("/{path}")).cloned()).unwrap_or_default()
    }

    /// title is the displayed title of a page: its number, if any, and title.
    pub(super) fn title(&self, d: &Doc) -> String {
        numbered(&self.number_of(d), &title_of(d))
    }

    /// anchorOf returns the anchor of a free field or section of d (and, for a
    /// section, its title). Equal anchors on one page are numbered -1, -2, ... in
    /// page order, as GitHub and the HTML build do, so a link never lands on a namesake.
    // ponytail: Markdown headings written inside body are not counted.
    pub(super) fn anchor_of(&self, d: &Doc, n: Option<&Node>) -> AnchorInfo {
        let key = d as *const Doc;
        let cached = self.slugs.borrow().get(&key).cloned();
        let m = match cached {
            Some(m) => m,
            None => {
                let mut m = HashMap::new();
                let mut used = HashSet::new();
                let mut add = |v: &Node, key: &str, section: bool, num: String| {
                    let base = engine::heading_anchor(key);
                    let mut id = base.clone();
                    let mut i = 1;
                    while used.contains(&id) {
                        id = format!("{base}-{i}");
                        i += 1;
                    }
                    used.insert(id.clone());
                    let info = if section {
                        AnchorInfo {
                            anchor: id,
                            title: one_line(key),
                            num,
                        }
                    } else {
                        AnchorInfo {
                            anchor: id,
                            ..Default::default()
                        }
                    };
                    m.insert(v as *const Node, info);
                };
                // sections are numbered under the page number, continuously across the fields of the page
                fn sections(
                    v: &Node,
                    prefix: &str,
                    count: &mut usize,
                    add: &mut dyn FnMut(&Node, &str, bool, String),
                ) {
                    for mem in &v.members {
                        if mem.key != engine::SECTIONS_KEY {
                            let mut num = String::new();
                            if !prefix.is_empty() {
                                *count += 1;
                                num = format!("{prefix}.{count}");
                            }
                            add(&mem.value, &mem.key, true, num.clone());
                            if engine::is_sections(&mem.value) {
                                let mut sub = 0;
                                sections(&mem.value, &num, &mut sub, add);
                            }
                        }
                    }
                }
                let mut top = 0;
                let page_num = self.number_of(d);
                for mem in &root(d).members {
                    if !reserved(&mem.key) && !is_empty(&mem.value) {
                        add(&mem.value, &mem.key, false, String::new());
                        if engine::is_sections(&mem.value) {
                            sections(&mem.value, &page_num, &mut top, &mut add);
                        }
                    }
                }
                let m = Rc::new(m);
                self.slugs.borrow_mut().insert(key, m.clone());
                m
            }
        };
        n.and_then(|n| m.get(&(n as *const Node)).cloned())
            .unwrap_or_default()
    }
}

/// PagePath is the page path of a document relative to the output directory.
pub fn page_path(d: &Doc) -> String {
    format!("{}.md", d.rel.strip_suffix(".json").unwrap_or(&d.rel))
}

/// root is the root object of a parsed document.
pub(super) fn root(d: &Doc) -> &Node {
    d.root().expect("a parsed document")
}

/// oneLine turns line breaks into spaces: titles are used in headings and
/// link texts, which must stay on one line.
pub(super) fn one_line(s: &str) -> String {
    s.replace("\r\n", " ").replace(['\n', '\r'], " ")
}

pub(super) fn title_of(d: &Doc) -> String {
    match root(d).get("title") {
        Some(t) if t.kind == Kind::String => one_line(&t.str),
        _ => d.id.clone(),
    }
}

/// numbered puts a number before a title.
pub(super) fn numbered(num: &str, title: &str) -> String {
    if num.is_empty() {
        return title.to_string();
    }
    format!("{num} {title}")
}

/// lf makes line breaks in generated text \n only.
pub(super) fn lf(s: &str) -> String {
    s.replace("\r\n", "\n").replace('\r', "\n")
}

/// relPath returns the relative path to `to` from the directory of the page
/// `from`; both are '/' paths relative to the output directory.
pub(super) fn rel_path(from: &str, to: &str) -> String {
    let from_dir: Vec<&str> = match from.rfind('/') {
        Some(i) => from[..i].split('/').collect(),
        None => Vec::new(),
    };
    let to_parts: Vec<&str> = to.split('/').collect();
    let mut n = 0;
    while n < from_dir.len() && n < to_parts.len() - 1 && from_dir[n] == to_parts[n] {
        n += 1;
    }
    "../".repeat(from_dir.len() - n) + &to_parts[n..].join("/")
}

/// heading turns a field name into a section heading: first letter upper
/// case, '_' and '-' become spaces.
pub(super) fn heading(key: &str) -> String {
    let k = key.replace(['_', '-'], " ");
    let mut cs = k.chars();
    match cs.next() {
        // utf8.DecodeRuneInString("") is RuneError, which ToUpper keeps
        None => "\u{FFFD}".to_string(),
        Some(c) => {
            // unicode.ToUpper: the simple mapping. Rust knows the full one; where
            // it is longer (ß -> SS) the rune stays, except the Greek letters with
            // ypogegrammeni, whose simple upper case is the prosgegrammeni form.
            let mut up = c.to_uppercase();
            let u = match (up.next(), up.next(), c as u32) {
                (Some(u), None, _) => u,
                (_, _, r @ (0x1F80..=0x1FA7)) if r & 0xF < 8 => char::from_u32(r + 8).unwrap(),
                (_, _, r @ (0x1FB3 | 0x1FC3 | 0x1FF3)) => char::from_u32(r + 9).unwrap(),
                _ => c,
            };
            let mut s = String::with_capacity(k.len());
            s.push(u);
            s.push_str(cs.as_str());
            s
        }
    }
}

/// anchorInfo is the anchor of a field or section; title is set for a section,
/// num for a section of a numbered page. The anchor never depends on the number.
#[derive(Debug, Clone, Default, PartialEq)]
pub(super) struct AnchorInfo {
    pub anchor: String,
    pub title: String,
    pub num: String,
}
