// Package render turns validated documents into Markdown pages (docs/out) and
// the audit build (docs/out-full).
package render

import (
	"sort"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/santiment/docc/internal/engine"
	"github.com/santiment/docc/internal/loader"
)

const Header = "<!-- GENERATED by docc, DO NOT EDIT -->"

// Renderer builds the files of one build.
type Renderer struct {
	P    *engine.Project
	Full bool

	back    map[string][]*engine.Doc
	slugs   map[*engine.Doc]map[*loader.Node]anchorInfo
	single  bool // single-file build: links are in-file anchors, no Header per page
	anchors bool // single Markdown file: emit <a id> before pages and field headings
	html    bool // single HTML file: pages carry only body and fields
}

// Files returns every generated file: path relative to the output directory
// ('/' separators) to content. Call it only when validation found no errors
// of groups 1xx and 2xx.
func (r *Renderer) Files() map[string]string {
	out := map[string]string{}
	for _, d := range r.docs() {
		out[PagePath(d)] = lf(r.page(d))
	}
	out["_tree.md"] = lf(r.tree())
	return out
}

// Single returns every page in one Markdown file: the document tree first,
// then the pages in tree order. Links become in-file anchors. Same call
// contract as Files.
func (r *Renderer) Single() string {
	s := *r
	s.single, s.anchors = true, true
	blocks := append([]string{Header}, s.treeBlocks()...)
	for _, d := range s.ordered() {
		blocks = append(blocks, "---", s.page(d))
	}
	return lf(strings.Join(blocks, "\n\n")) + "\n"
}

// ordered returns the pages in tree order; documents the tree walk cannot reach
// (a parent cycle) follow, so that nothing is lost.
func (r *Renderer) ordered() []*engine.Doc {
	tree, orphans := r.layout()
	seen := map[string]bool{}
	var out []*engine.Doc
	for _, e := range append(tree, orphans...) {
		seen[e.d.ID] = true
		out = append(out, e.d)
	}
	for _, d := range r.docs() {
		if !seen[d.ID] {
			out = append(out, d)
		}
	}
	return out
}

// PagePath is the page path of a document relative to the output directory.
func PagePath(d *engine.Doc) string { return strings.TrimSuffix(d.Rel, ".json") + ".md" }

// docs returns the documents that get a page, ordered by path.
func (r *Renderer) docs() []*engine.Doc {
	var out []*engine.Doc
	for _, d := range r.P.Docs {
		if r.P.Graph[d.ID] == d && d.Parsed() && (r.Full || !d.Hidden) {
			out = append(out, d)
		}
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].Rel < out[j].Rel })
	return out
}

// hasPage reports whether links may point at the document.
func (r *Renderer) hasPage(d *engine.Doc) bool {
	return d != nil && r.P.Graph[d.ID] == d && d.Parsed() && (r.Full || !d.Hidden)
}

// oneLine turns line breaks into spaces: titles are used in headings and
// link texts, which must stay on one line.
var oneLine = strings.NewReplacer("\r\n", " ", "\n", " ", "\r", " ")

func titleOf(d *engine.Doc) string {
	if t := d.Root.Get("title"); t != nil && t.Kind == loader.String {
		return oneLine.Replace(t.Str)
	}
	return d.ID
}

// lf makes line breaks in generated text \n only.
func lf(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "\r\n", "\n"), "\r", "\n")
}

// relPath returns the relative path to `to` from the directory of the page
// `from`; both are '/' paths relative to the output directory.
func relPath(from, to string) string {
	var fromDir []string
	if i := strings.LastIndexByte(from, '/'); i >= 0 {
		fromDir = strings.Split(from[:i], "/")
	}
	toParts := strings.Split(to, "/")
	n := 0
	for n < len(fromDir) && n < len(toParts)-1 && fromDir[n] == toParts[n] {
		n++
	}
	var b strings.Builder
	for i := n; i < len(fromDir); i++ {
		b.WriteString("../")
	}
	b.WriteString(strings.Join(toParts[n:], "/"))
	return b.String()
}

// heading turns a field name into a section heading: first letter upper
// case, '_' and '-' become spaces.
func heading(key string) string {
	k := strings.NewReplacer("_", " ", "-", " ").Replace(key)
	r, n := utf8.DecodeRuneInString(k)
	return string(unicode.ToUpper(r)) + k[n:]
}

// anchor builds the heading anchor: lower case, spaces to '-', punctuation
// dropped, Unicode letters kept.
func anchor(h string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(h) {
		switch {
		case r == ' ':
			b.WriteByte('-')
		case unicode.IsLetter(r) || unicode.IsDigit(r) || r == '-' || r == '_':
			b.WriteRune(r)
		}
	}
	return b.String()
}

// anchorInfo is the anchor of a field or section; title is set for a section.
type anchorInfo struct{ anchor, title string }

// anchorOf returns the anchor of a free field or section of d (and, for a
// section, its title). Equal anchors on one page are numbered -1, -2, ... in
// page order, as GitHub and the HTML build do, so a link never lands on a namesake.
// ponytail: Markdown headings written inside body are not counted.
func (r *Renderer) anchorOf(d *engine.Doc, n *loader.Node) anchorInfo {
	if r.slugs == nil {
		r.slugs = map[*engine.Doc]map[*loader.Node]anchorInfo{}
	}
	m, ok := r.slugs[d]
	if !ok {
		m = map[*loader.Node]anchorInfo{}
		r.slugs[d] = m
		used := map[string]bool{}
		add := func(v *loader.Node, key string, section bool) {
			base := anchor(heading(key))
			id := base
			for i := 1; used[id]; i++ {
				id = base + "-" + strconv.Itoa(i)
			}
			used[id] = true
			m[v] = anchorInfo{anchor: id}
			if section {
				m[v] = anchorInfo{id, oneLine.Replace(key)}
			}
		}
		var sections func(v *loader.Node)
		sections = func(v *loader.Node) {
			for _, mem := range v.Members {
				if mem.Key != engine.SectionsKey {
					add(mem.Value, mem.Key, true)
					if engine.IsSections(mem.Value) {
						sections(mem.Value)
					}
				}
			}
		}
		for _, mem := range d.Root.Members {
			if !reserved[mem.Key] && !isEmpty(mem.Value) {
				add(mem.Value, mem.Key, false)
				if engine.IsSections(mem.Value) {
					sections(mem.Value)
				}
			}
		}
	}
	return m[n]
}
