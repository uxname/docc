func TestHTMLBuild(t *testing.T) {
	project(t, map[string]string{
		"docs/src/index.json": `{"title":"Index <b>","body":["See [[req#statement]] and [[req]].","<script>alert(1)</script> text"]}`,
		"docs/src/req.json": `{"title":"Req","kind":"requirement","status":"accepted","priority":2,"tags":["t1"],
			"parent":"index","statement":["Fact.","More."],"owner":"Team","stage":"alpha",
			"body":"Click <a id=\"x\" onclick=\"evil()\">here</a>.","rows":[{"a":"one\ntwo","b":"x"}]}`,
		"docs/src/h.json":               `{"title":"Hid","hidden":true,"parent":"index","body":"Secret"}`,
		"docs/schemas/requirement.json": `{"additionalProperties":true,"x-docc-covered":true}`,
	})
	if code, out, errs := do("build", "--html"); code != 0 || !strings.Contains(out, "built docs/out.html") {
		t.Fatalf("%d %s %s", code, out, errs)
	}
	a := readApp(t, "docs/out.html")
	ps := a.Data.Pages
	// pages in tree order (the page script links neighbours by it), with their parts as data
	if len(ps) != 2 || ps[0].ID != "index" || ps[0].Title != "Index <b>" || ps[1].ID != "req" {
		t.Fatalf("pages: %+v", ps)
	}
	req := ps[1]
	if req.Kind != "requirement" || req.Status != "accepted" || req.SC != "ok" || req.Priority != "2" ||
		strings.Join(req.Tags, ",") != "t1" || strings.Join(req.Crumbs, ",") != "index" || req.Parent != "index" ||
		strings.Join(ps[0].Kids, ",") != "req" {
		t.Errorf("req: %+v", req)
	}
	// one-line fields form a property list
	if len(req.Props) != 2 || req.Props[0].K != "Owner" || req.Props[0].ID != "req--owner" || req.Props[0].H != "Team" || req.Props[0].P != "/owner" {
		t.Errorf("props: %+v", req.Props)
	}
	for _, want := range []string{
		`<h2 id="req--statement">Statement</h2>`, // target of [[req#statement]]
		`<a href="#req--statement">Req</a>`,      // the link itself
		`<a href="#req">Req</a>`,                 // plain page link
		"<td>one<br>two</td>",                    // line break in a table cell survives
	} {
		if !strings.Contains(a.Blocks, want) {
			t.Errorf("blocks lack %q", want)
		}
	}
	for _, want := range []string{"<title>Index &lt;b&gt;</title>", `type="search"`, `prefers-color-scheme`, `@media print`} {
		if !strings.Contains(a.Shell, want) {
			t.Errorf("out.html lacks %q", want)
		}
	}
	// agents' raw HTML never reaches the blocks; hidden documents stay out; nothing is fetched
	for _, bad := range []string{"<script>alert", "onclick", "evil", ".md\"", "<h2 id=\"req--owner\""} {
		if strings.Contains(a.Blocks, bad) {
			t.Errorf("blocks contain %q", bad)
		}
	}
	page := readFile(t, "docs/out.html")
	for _, bad := range []string{"Secret", "Hid", "<script src", "<link", "</script>alert", "<script>alert"} {
		if strings.Contains(page, bad) {
			t.Errorf("out.html contains %q", bad)
		}
	}
	before := readFile(t, "docs/out.html")
	do("build", "--html")
	if readFile(t, "docs/out.html") != before {
		t.Error("the second build changed the file")
	}
	do("build", "--full", "--html")
	if full := readFile(t, "docs/out-full.html"); !strings.Contains(full, "Secret") {
		t.Error("out-full.html lacks the hidden document")
	}
}

func TestTreeSortsSiblingsByTitle(t *testing.T) {
	project(t, map[string]string{
		"docs/src/index.json": `{"title":"Index","body":"b"}`,
		"docs/src/a1.json":    `{"title":"Яблоко","parent":"index"}`,
		"docs/src/a2.json":    `{"title":"apple","parent":"index"}`,
		"docs/src/a3.json":    `{"title":"Zebra","parent":"index"}`,
		"docs/src/a4.json":    `{"title":"ёлка","parent":"index"}`,
		"docs/src/a5.json":    `{"title":"Ель","parent":"index"}`,
		"docs/src/a6.json":    `{"title":"10 Ten","parent":"index"}`,
		"docs/src/a7.json":    `{"title":"2 Two","parent":"index"}`,
		"docs/src/b2.json":    `{"title":"Same","parent":"index"}`,
		"docs/src/b1.json":    `{"title":"Same","parent":"index"}`,
	})
	if code, out, errs := do("build"); code != 0 {
		t.Fatalf("%d %s %s", code, out, errs)
	}
	tree := readFile(t, "docs/out/_tree.md")
	var got []string
	for _, l := range strings.Split(tree, "\n") {
		if m := regexp.MustCompile(`^\s+- \[(.+?)\]\((.+?)\.md\)`).FindStringSubmatch(l); m != nil {
			got = append(got, m[1]+"="+m[2])
		}
	}
	want := "2 Two=a7 10 Ten=a6 apple=a2 Same=b1 Same=b2 Zebra=a3 ёлка=a4 Ель=a5 Яблоко=a1"
	if strings.Join(got, " ") != want {
		t.Errorf("order:\n got %s\nwant %s\n%s", strings.Join(got, " "), want, tree)
	}
}

const sectionsAudit = `{"title":"Audit","parent":"index","body":"Intro.",
	"17.1 Critical":{"$sections":true,
		"17.1.2 No renewal date":["Rule needs a date.","Open: [[questions#Renewal date]]."],
		"Empty one":"",
		"Deeper":{"$sections":true,"Same":"deep text"},
		"Same":"top text"},
	"Plain":{"timeout":"5s"}}`

func sectionsProject(t *testing.T, audit string) {
	project(t, map[string]string{
		"docs/src/index.json":     `{"title":"Index","body":"See [[audit]] and [[questions]]."}`,
		"docs/src/audit.json":     audit,
		"docs/src/questions.json": `{"title":"Questions","parent":"index","Renewal date":"See [[audit#17.1 Critical/17.1.2 No renewal date]] and [[audit#17.1 Critical/Deeper/Same]] and [[audit#17.1 Critical/Same]].","Copy":"{{audit#17.1 Critical/Deeper/Same}}"}`,
	})
}

func TestSectionsRenderLinkAndInclude(t *testing.T) {
	sectionsProject(t, sectionsAudit)
	if code, out, errs := do("build", "--single"); code != 0 {
		t.Fatalf("%d %s %s", code, out, errs)
	}
	audit := readFile(t, "docs/out/audit.md")
	for _, want := range []string{
		"## 17.1 Critical\n\n### 17.1.2 No renewal date\n\nRule needs a date.",
		"### Empty one\n\n### Deeper\n\n#### Same\n\ndeep text\n\n### Same\n\ntop text",
		"## Plain\n\n- **timeout:** 5s",                 // a list object is unchanged
		"Open: [Questions](questions.md#renewal-date).", // a link to a field keeps the title of the document
	} {
		if !strings.Contains(audit, want) {
			t.Errorf("audit.md lacks %q:\n%s", want, audit)
		}
	}
	if strings.Contains(audit, "$sections") {
		t.Errorf("the marker leaks:\n%s", audit)
	}
	q := readFile(t, "docs/out/questions.md")
	// the first Same is "same", the second "same-1", and each link follows its own
	for _, want := range []string{
		"[17.1.2 No renewal date](audit.md#1712-no-renewal-date)", "[Same](audit.md#same)", "[Same](audit.md#same-1)", "deep text",
	} {
		if !strings.Contains(q, want) {
			t.Errorf("questions.md lacks %q:\n%s", want, q)
		}
	}
	one := readFile(t, "docs/out.md")
	for _, want := range []string{`<a id="audit--1712-no-renewal-date"></a>`, "(#audit--same-1)", "(#audit--1712-no-renewal-date)"} {
		if !strings.Contains(one, want) {
			t.Errorf("out.md lacks %q", want)
		}
	}
	if code, out, errs := do("build", "--html"); code != 0 {
		t.Fatalf("%d %s %s", code, out, errs)
	}
	page := readApp(t, "docs/out.html").Blocks
	for _, want := range []string{`<h3 id="audit--1712-no-renewal-date"`, `<h4 id="audit--same"`, `<h3 id="audit--same-1"`, `href="#audit--same-1"`} {
		if !strings.Contains(page, want) {
			t.Errorf("out.html lacks %q", want)
		}
	}
}

func TestSectionsAnchorCheck(t *testing.T) {
	sectionsProject(t, sectionsAudit)
	if code, out, errs := do("validate"); code != 0 {
		t.Fatalf("a valid path is rejected: %d %s %s", code, out, errs)
	}
	renamed := strings.Replace(sectionsAudit, "17.1.2 No renewal date", "17.1.2 Renamed", 1)
	sectionsProject(t, renamed)
	code, out, _ := do("validate")
	if code == 0 || !strings.Contains(out, "DOC312") || !strings.Contains(out, "17.1 Critical/17.1.2 No renewal date") {
		t.Errorf("a renamed section passes DOC312: %d %s", code, out)
	}
	// a plain object is not a set of sections: its keys are no anchors
	sectionsProject(t, strings.Replace(sectionsAudit, `"Plain":{"timeout":"5s"}`, `"Plain":{"timeout":"5s"},"Other":"[[audit#Plain/timeout]]"`, 1))
	if code, out, _ := do("validate"); code == 0 || !strings.Contains(out, "DOC312") {
		t.Errorf("a key of a list object is an anchor: %d %s", code, out)
	}
}

