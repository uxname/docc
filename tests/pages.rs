#[test]
fn sections_ignore_path() {
    let p = sections_project(&SECTIONS_AUDIT.replacen(r#""Empty one":"""#, r#""Empty one":"Very important text. [[audit#Nowhere]]""#, 1));
    let (code, out, _) = p.run(&["validate"]);
    assert!(code != 0 && out.contains("DOC312"), "setup: {code} {out}");
    let ignored = SECTIONS_AUDIT.replacen(r#""Empty one":"""#, r#""Empty one":"Very important text. [[audit#Nowhere]]""#, 1);
    let ignored = ignored.replacen(
        r#""Plain""#,
        r#""docIgnore":[{"rule":"DOC312","reason":"r","path":"/17.1 Critical/Empty one"}],"Plain""#,
        1,
    );
    let p = sections_project(&ignored);
    let (code, out, errs) = p.run(&["validate"]);
    assert_eq!(code, 0, "docIgnore.path on a section: {out} {errs}");
}

