fn strs(v: &Value) -> String {
    v.as_array().into_iter().flatten().map(|x| x.as_str().unwrap_or("")).collect::<Vec<_>>().join(",")
}

#[test]
fn html_build() {
    let p = project([
        ("docs/src/index.json", r#"{"title":"Index <b>","body":["See [[req#statement]] and [[req]].","<script>alert(1)</script> text"]}"#),
        (
            "docs/src/req.json",
            r#"{"title":"Req","kind":"requirement","status":"accepted","priority":2,"tags":["t1"],
			"parent":"index","statement":["Fact.","More."],"owner":"Team","stage":"alpha",
			"body":"Click <a id=\"x\" onclick=\"evil()\">here</a>.","rows":[{"a":"one\ntwo","b":"x"}]}"#,
        ),
        ("docs/src/h.json", r#"{"title":"Hid","hidden":true,"parent":"index","body":"Secret"}"#),
        ("docs/schemas/requirement.json", r#"{"additionalProperties":true,"x-docc-covered":true}"#),
    ]);
    let (code, out, errs) = p.run(&["build", "--html"]);
    assert!(code == 0 && out.contains("built docs/out.html"), "{code} {out} {errs}");
    let a = read_app(&p, "docs/out.html");
    let ps = a.pages();
    // pages in tree order (the page script links neighbours by it), with their parts as data
    assert!(
        ps.len() == 2 && s(&ps[0], "id") == "index" && s(&ps[0], "title") == "Index <b>" && s(&ps[1], "id") == "req",
        "pages: {ps:?}"
    );
    let req = &ps[1];
    assert!(
        s(req, "kind") == "requirement"
            && s(req, "status") == "accepted"
            && s(req, "sc") == "ok"
            && s(req, "priority") == "2"
            && strs(&req["tags"]) == "t1"
            && strs(&req["crumbs"]) == "index"
            && s(req, "parent") == "index"
            && strs(&ps[0]["kids"]) == "req",
        "req: {req}"
    );
    // one-line fields form a property list
    let props = req["props"].as_array().cloned().unwrap_or_default();
    assert!(
        props.len() == 2
            && s(&props[0], "k") == "Owner"
            && s(&props[0], "id") == "req--owner"
            && s(&props[0], "h") == "Team"
            && s(&props[0], "p") == "/owner",
        "props: {props:?}"
    );
    for want in [
        r#"<h2 id="req--statement">Statement</h2>"#, // target of [[req#statement]]
        r##"<a href="#req--statement">Req</a>"##,    // the link itself
        r##"<a href="#req">Req</a>"##,               // plain page link
        "<td>one<br>two</td>",                       // line break in a table cell survives
    ] {
        assert!(a.blocks.contains(want), "blocks lack {want:?}");
    }
    for want in ["<title>Index &lt;b&gt;</title>", r#"type="search""#, "prefers-color-scheme", "@media print"] {
        assert!(a.shell.contains(want), "out.html lacks {want:?}");
    }
    // agents' raw HTML never reaches the blocks; hidden documents stay out; nothing is fetched
    for bad in ["<script>alert", "onclick", "evil", ".md\"", "<h2 id=\"req--owner\""] {
        assert!(!a.blocks.contains(bad), "blocks contain {bad:?}");
    }
    let page = p.read("docs/out.html");
    for bad in ["Secret", "Hid", "<script src", "<link", "</script>alert", "<script>alert"] {
        assert!(!page.contains(bad), "out.html contains {bad:?}");
    }
    let before = p.read("docs/out.html");
    p.run(&["build", "--html"]);
    assert_eq!(p.read("docs/out.html"), before, "the second build changed the file");
    p.run(&["build", "--full", "--html"]);
    assert!(p.read("docs/out-full.html").contains("Secret"), "out-full.html lacks the hidden document");
}

#[test]
fn tree_sorts_siblings_by_title() {
    let p = project([
        ("docs/src/index.json", r#"{"title":"Index","body":"b"}"#),
        ("docs/src/a1.json", r#"{"title":"Яблоко","parent":"index"}"#),
        ("docs/src/a2.json", r#"{"title":"apple","parent":"index"}"#),
        ("docs/src/a3.json", r#"{"title":"Zebra","parent":"index"}"#),
        ("docs/src/a4.json", r#"{"title":"ёлка","parent":"index"}"#),
        ("docs/src/a5.json", r#"{"title":"Ель","parent":"index"}"#),
        ("docs/src/a6.json", r#"{"title":"10 Ten","parent":"index"}"#),
        ("docs/src/a7.json", r#"{"title":"2 Two","parent":"index"}"#),
        ("docs/src/b2.json", r#"{"title":"Same","parent":"index"}"#),
        ("docs/src/b1.json", r#"{"title":"Same","parent":"index"}"#),
    ]);
    let (code, out, errs) = p.run(&["build"]);
    assert_eq!(code, 0, "{out} {errs}");
    let tree = p.read("docs/out/_tree.md");
    // Go's \s is ASCII
    let re = Regex::new(r"^[\t\n\f\r ]+- \[(.+?)\]\((.+?)\.md\)").unwrap();
    let got: Vec<String> = tree.split('\n').filter_map(|l| re.captures(l)).map(|m| format!("{}={}", &m[1], &m[2])).collect();
    let want = "2 Two=a7 10 Ten=a6 apple=a2 Same=b1 Same=b2 Zebra=a3 ёлка=a4 Ель=a5 Яблоко=a1";
    assert_eq!(got.join(" "), want, "order:\n{tree}");
}

const SECTIONS_AUDIT: &str = r#"{"title":"Audit","parent":"index","body":"Intro.",
	"17.1 Critical":{"$sections":true,
		"17.1.2 No renewal date":["Rule needs a date.","Open: [[questions#Renewal date]]."],
		"Empty one":"",
		"Deeper":{"$sections":true,"Same":"deep text"},
		"Same":"top text"},
	"Plain":{"timeout":"5s"}}"#;

fn sections_project(audit: &str) -> Dir {
    project([
        ("docs/src/index.json", r#"{"title":"Index","body":"See [[audit]] and [[questions]]."}"#),
        ("docs/src/audit.json", audit),
        (
            "docs/src/questions.json",
            r#"{"title":"Questions","parent":"index","Renewal date":"See [[audit#17.1 Critical/17.1.2 No renewal date]] and [[audit#17.1 Critical/Deeper/Same]] and [[audit#17.1 Critical/Same]].","Copy":"{{audit#17.1 Critical/Deeper/Same}}"}"#,
        ),
    ])
}

#[test]
fn sections_render_link_and_include() {
    let p = sections_project(SECTIONS_AUDIT);
    let (code, out, errs) = p.run(&["build", "--single"]);
    assert_eq!(code, 0, "{out} {errs}");
    let audit = p.read("docs/out/audit.md");
    for want in [
        "## 17.1 Critical\n\n### 17.1.2 No renewal date\n\nRule needs a date.",
        "### Empty one\n\n### Deeper\n\n#### Same\n\ndeep text\n\n### Same\n\ntop text",
        "## Plain\n\n- **timeout:** 5s",                 // a list object is unchanged
        "Open: [Questions](questions.md#renewal-date).", // a link to a field keeps the title of the document
    ] {
        assert!(audit.contains(want), "audit.md lacks {want:?}:\n{audit}");
    }
    assert!(!audit.contains("$sections"), "the marker leaks:\n{audit}");
    let q = p.read("docs/out/questions.md");
    // the first Same is "same", the second "same-1", and each link follows its own
    for want in ["[17.1.2 No renewal date](audit.md#1712-no-renewal-date)", "[Same](audit.md#same)", "[Same](audit.md#same-1)", "deep text"] {
        assert!(q.contains(want), "questions.md lacks {want:?}:\n{q}");
    }
    let one = p.read("docs/out.md");
    for want in [r#"<a id="audit--1712-no-renewal-date"></a>"#, "(#audit--same-1)", "(#audit--1712-no-renewal-date)"] {
        assert!(one.contains(want), "out.md lacks {want:?}");
    }
    let (code, out, errs) = p.run(&["build", "--html"]);
    assert_eq!(code, 0, "{out} {errs}");
    let page = read_app(&p, "docs/out.html").blocks;
    for want in [r#"<h3 id="audit--1712-no-renewal-date""#, r#"<h4 id="audit--same""#, r#"<h3 id="audit--same-1""#, r##"href="#audit--same-1""##] {
        assert!(page.contains(want), "out.html lacks {want:?}");
    }
}

#[test]
fn sections_anchor_check() {
    let p = sections_project(SECTIONS_AUDIT);
    let (code, out, errs) = p.run(&["validate"]);
    assert_eq!(code, 0, "a valid path is rejected: {out} {errs}");
    let renamed = SECTIONS_AUDIT.replacen("17.1.2 No renewal date", "17.1.2 Renamed", 1);
    let p = sections_project(&renamed);
    let (code, out, _) = p.run(&["validate"]);
    assert!(
        code != 0 && out.contains("DOC312") && out.contains("17.1 Critical/17.1.2 No renewal date"),
        "a renamed section passes DOC312: {code} {out}"
    );
    // a plain object is not a set of sections: its keys are no anchors
    let p = sections_project(&SECTIONS_AUDIT.replacen(
        r#""Plain":{"timeout":"5s"}"#,
        r#""Plain":{"timeout":"5s"},"Other":"[[audit#Plain/timeout]]""#,
        1,
    ));
    let (code, out, _) = p.run(&["validate"]);
    assert!(code != 0 && out.contains("DOC312"), "a key of a list object is an anchor: {code} {out}");
}

