#[test]
fn page_meta_relations_and_table() {
    let p = project([
        ("docc.json", r#"{"trace":{"scan":["code/**"]}}"#),
        ("code/a.go", "package a\n\n// docc: req\n"),
        ("docs/src/index.json", r#"{"title":"Index","body":"Start with [[req]]."}"#),
        (
            "docs/src/req.json",
            r#"{"title":"Req","kind":"requirement","status":"accepted","priority":2,"tags":["x","y"],
			"parent":"index","body":"Text.",
			"acceptance":[{"given":"A","when":"B","then":"C | D"},{"given":"E","when":"F","then":"G"}]}"#,
        ),
        ("docs/src/bare.json", r#"{"title":"Bare","kind":"requirement","parent":"index"}"#),
        ("docs/schemas/requirement.json", r#"{"additionalProperties":true,"x-docc-covered":true}"#),
    ]);
    let (code, out, errs) = p.run(&["build"]);
    assert_eq!(code, 0, "{out} {errs}");
    let req = p.read("docs/out/req.md");
    for want in [
        "# Req\n\nrequirement · accepted · priority 2 · x, y\n\nText.",
        "| given | when | then |\n| --- | --- | --- |\n| A | B | C \\| D |",
        "## Parent\n\n[Index](index.md)",
        "## Referenced by\n\n- [Index](index.md)",
        "## Covered by\n\n- `code/a.go`",
    ] {
        assert!(req.contains(want), "req.md lacks {want:?}:\n{req}");
    }
    assert!(
        !req.contains("## Kind") && !req.contains("## Tags") && !req.contains("## Status"),
        "old metadata sections:\n{req}"
    );
    let idx = p.read("docs/out/index.md");
    assert!(
        idx.contains("## Referenced by\n\n- [Bare](bare.md)\n- [Req](req.md)") && idx.ends_with("Document tree: [_tree.md](_tree.md)\n"),
        "index.md:\n{idx}"
    );
    let tree = p.read("docs/out/_tree.md");
    let bad = !tree.contains("## Documents without code coverage\n\n- [Bare](bare.md)")
        || tree.contains("- [Req](req.md)\n\n")
            && tree.split_once("without code coverage").is_some_and(|(_, rest)| rest.contains("[Req]"));
    assert!(!bad, "_tree.md:\n{tree}");
}

#[test]
fn output_has_no_cyrillic() {
    let p = project([
        (
            "docs/src/index.json",
            r#"{"title":"I","notes":["n"],"docIgnore":[{"rule":"DOC303","reason":"r","path":"/body"}],"body":"b"}"#,
        ),
        ("docs/src/h.json", r#"{"title":"H","hidden":true,"parent":"index"}"#),
    ]);
    p.run(&["build"]);
    p.run(&["build", "--full"]);
    let cyr = Regex::new("[А-Яа-яЁё]").unwrap();
    for dir in ["docs/out", "docs/out-full"] {
        let ents: Vec<_> = std::fs::read_dir(p.join(dir)).unwrap_or_else(|e| panic!("{dir}: {e}")).flatten().collect();
        assert!(!ents.is_empty(), "{dir}: empty");
        for e in ents {
            let name = e.file_name().to_string_lossy().into_owned();
            let s = p.read(&format!("{dir}/{name}"));
            assert!(!cyr.is_match(&s), "{dir}/{name} has Cyrillic:\n{s}");
        }
    }
    assert!(
        p.read("docs/out-full/_tree.md").contains("> full build: includes hidden documents and notes — do not publish"),
        "full tree banner missing"
    );
}

#[test]
fn single_file_build() {
    let p = project([
        ("docs/src/index.json", r#"{"title":"Index","body":"See [[req#statement]] and [[req]]."}"#),
        ("docs/src/req.json", r#"{"title":"Req","parent":"index","statement":"Fact."}"#),
        ("docs/src/h.json", r#"{"title":"Hid","hidden":true,"parent":"index","body":"Secret","notes":["n"]}"#),
    ]);
    let (code, out, errs) = p.run(&["build", "--single"]);
    assert!(code == 0 && out.contains("built docs/out.md"), "{code} {out} {errs}");
    let one = p.read("docs/out.md");
    for want in [
        "- [Index](#index)\n  - [Req](#req)",
        r#"<a id="index"></a>"#,
        r#"<a id="req"></a>"#,
        r#"<a id="req--statement"></a>"#,
        "See [Req](#req--statement) and [Req](#req).",
        "## Parent\n\n[Index](#index)",
    ] {
        assert!(one.contains(want), "out.md lacks {want:?}:\n{one}");
    }
    // links never point at files, hidden documents and the tree file stay out
    for bad in [".md)", "_tree.md", "Secret", "Hid"] {
        assert!(!one.contains(bad), "out.md contains {bad:?}:\n{one}");
    }
    // pages follow the tree order, the header comes once
    assert!(
        one.matches("GENERATED by docc").count() == 1 && one.find(r#"<a id="index">"#) <= one.find(r#"<a id="req">"#),
        "order or header:\n{one}"
    );
    let (code, out, _) = p.run(&["check"]);
    assert_eq!(code, 0, "check does not care about the single file: {out}");
    p.run(&["build", "--full", "--single"]);
    let full = p.read("docs/out-full.md");
    assert!(full.contains("Secret") && full.contains("(hidden)"), "out-full.md:\n{full}");
}

